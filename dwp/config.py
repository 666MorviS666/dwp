# Общий ECE усредняет по всем строкам и потому обещает больше, чем есть:
# на поздних минутах модель ошибается заметно сильнее. Тройки —
# (минута от, минута до, средний ECE внутри отрезка). Граница «до» не
# включается, None означает «и дальше».
#
# ИЗМЕРЕНО, а не выбрано: python -m dwp.calibcheck, десять разбиений,
# 7434 матча, патчи 59-60. По отрезкам ECE и стандартная ошибка среднего:
#   0-9   0.0185 ± 0.0019     30-39  0.0214 ± 0.0017
#   10-19 0.0183 ± 0.0020     40-49  0.0342 ± 0.0034
#   20-29 0.0231 ± 0.0012     50+    0.0753 ± 0.0078
# Первые четыре отрезка неразличимы между собой и слиты в один ярус.
# Три яруса не пересекаются даже интервалами в две стандартные ошибки.
#
# ЧЕГО ЭТИ ЧИСЛА НЕ ПОКРЫВАЮТ. Померены на полном наборе признаков из
# выгрузки, включая байбэки, которых в лайве нет. Для модели, обученной
# с --live-features, калибровка может отличаться, и сильнее всего там же,
# где отрезок и так самый шаткий — после 50-й минуты.
#
# И ещё: обещать ярус можно, а конкретное число, померенное на одном
# прогоне, нельзя. Проверено отдельно — полоса, посчитанная на
# калибровочной выборке, с тестовой по разбиениям не коррелирует
# (для 50+ обещанное 0.0233 обернулось 0.0767 на том же сиде).
# Поэтому здесь константа из многих разбиений, а не запись в артефакт.
