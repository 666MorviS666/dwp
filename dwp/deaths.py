"""Кто сейчас мёртв. Правило выведено из данных, а не из справочника.

ЗАДАЧА. `GetRealtimeStats` не отдаёт ни флага «жив», ни таймера
возрождения — у игрока есть только счётчики и координаты (полный список
полей проверяет `dwp.check_schema`). А на карте мёртвый герой обязан
выглядеть мёртвым, иначе картинка врёт: пять иконок стоят на месте
замеса, хотя четверых там уже нет.

ЧТО ИЗМЕРЕНО. Проба на живом матче (84 опроса раз в 2 с, 10 игроков,
7 смертей) показала: **координаты убитого героя замирают в точке смерти и
снова начинают меняться в момент возрождения**. Длительность простоя
совпала с таймерами возрождения Dota:

    уровень 14   46 и 48 с      уровень 19   69 с
    уровень 18   66 с           уровень 22   84 с

Простой всегда чуть длиннее табличного времени — на столько, сколько
возрождённый герой ещё стоит на фонтане, прежде чем пойти. Это и есть
единственная неточность правила, и она в безопасную сторону: герой
показан мёртвым чуть дольше, чем был, но никогда — живым, пока мёртв.

ПОЧЕМУ НЕ ТАБЛИЦА ВОЗРОЖДЕНИЯ. Её пришлось бы взять из интернета и
подписать как допущение — а таблицы Valve меняются патчами. В этом
проекте так уже обожглись однажды: справочная таблица опыта завышала
уровень у 82% игроков, и её заменили выведенной из данных
(`config.XP_TO_LEVEL`). Здесь того же удалось избежать вовсе: признак
«координаты стоят» приходит из того же ответа, что и всё остальное, и
проверяется тем же способом.

ЧЕГО ПРАВИЛО НЕ ЗНАЕТ. Подключились к матчу в середине — про тех, кто
уже лежит, мы не знаем ничего: их смерть случилась до первого опроса, и
счётчик её не покажет. Такие герои считаются живыми до первой смерти при
нас. Это честнее, чем гадать, и видно по `known`.
"""

from __future__ import annotations

from .killfeed import _players

# На сколько координаты должны разойтись, чтобы считать это движением.
#
# ЗАМЕРЕНО (1300 пар соседних опросов, 10 игроков, живой матч):
#     координата не менялась ВОВСЕ       957 пар — разница ровно 0.0
#     координата менялась                343 пары, минимум 1.372e-04
# То есть дрожания в этом источнике нет: стоящий герой отдаёт тот же самый
# float бит в бит, а самый мелкий настоящий шаг на два порядка крупнее
# любого мыслимого порога. Порог всё равно оставлен ненулевым — на случай,
# если Valve однажды начнёт слать координаты с шумом, — но взят заведомо
# ниже наблюдённого минимума, чтобы не съесть медленный шаг.
MOVE_EPS = 1e-5


class Deaths:
    """Состояние «жив/мёртв» по каждому игроку одного матча.

    Заводится заново на каждый матч, как и `killfeed.Feed`: счётчики
    прошлого матча к новому отношения не имеют.
    """

    def __init__(self) -> None:
        self.prev: dict | None = None
        # ключ игрока -> {dead, since, xy, deaths, known}
        self.st: dict[tuple, dict] = {}
        # Сколько смертей вообще прошло у нас на глазах. Считается всегда,
        # даже когда координат нет: это факт из счётчика, и он не зависит
        # от того, можем ли мы сказать, ЛЕЖИТ ли герой прямо сейчас.
        self.seen = 0

    def update(self, payload: dict, minute: float) -> None:
        cur = _players(payload)
        for key, p in cur.items():
            xy = (p.get("x"), p.get("y"))
            has_xy = xy[0] is not None and xy[1] is not None
            old = self.st.get(key)
            prev_p = (self.prev or {}).get(key)
            if old is None:
                self.st[key] = {"dead": False, "since": None, "xy": xy,
                                "deaths": p["d"], "known": False}
                continue
            died = prev_p is not None and p["d"] > prev_p["d"]
            if died:
                # По ПРИРОСТУ, а не по факту: между двумя опросами герой
                # может умереть дважды (выкупился и умер снова), и тогда
                # счётчик прыгает на два. Считать такое за одну смерть —
                # тихо терять события; на реплее это дало 87 вместо 89.
                self.seen += int(p["d"]) - int(prev_p["d"])
            # БЕЗ КООРДИНАТ «МЁРТВ» НЕ СТАВИТСЯ ВОВСЕ. Правило целиком
            # держится на том, что точка замирает и потом идёт; если точки
            # нет, снять признак будет нечем, и герой останется мёртвым до
            # конца матча — то есть ошибка будет не «на несколько секунд»,
            # а навсегда. Такое молчаливое «мёртв» хуже честного «не знаю».
            # В бою координаты есть всегда (проверено на живом матче); их
            # нет только в офлайн-реплее, где карта и не рисуется.
            if died and has_xy:
                old.update({"dead": True, "since": float(minute) if minute == minute
                            else None, "xy": xy, "known": True})
            elif died:
                old.update({"known": True})
            elif old["dead"] and has_xy and old["xy"][0] is not None:
                # Возрождение видно по тому, что точка сдвинулась. Пока
                # герой стоит, отличить «лежит» от «стоит на фонтане» из
                # этого ответа нельзя — и мы не отличаем, а не угадываем.
                dx = abs(float(xy[0]) - float(old["xy"][0]))
                dy = abs(float(xy[1]) - float(old["xy"][1]))
                if dx > MOVE_EPS or dy > MOVE_EPS:
                    old.update({"dead": False, "since": None, "xy": xy})
            elif not old["dead"]:
                old["xy"] = xy
            old["deaths"] = p["d"]
        self.prev = cur

    def state(self, team: int, slot: int) -> dict:
        return self.st.get((int(team), int(slot))) or {
            "dead": False, "since": None, "known": False}

    def by_hero(self) -> dict[tuple, dict]:
        """{(команда, герой): состояние} — так его читает карта."""
        out = {}
        for key, v in self.st.items():
            p = (self.prev or {}).get(key)
            if not p:
                continue
            out[(int(p["team"]), int(p["hero"]))] = v
        return out

    @property
    def n_dead(self) -> int:
        """Сколько героев лежит ПРЯМО СЕЙЧАС. Без координат всегда 0."""
        return sum(1 for v in self.st.values() if v["dead"])

    @property
    def n_seen(self) -> int:
        """Сколько смертей прошло у нас на глазах за матч."""
        return self.seen
